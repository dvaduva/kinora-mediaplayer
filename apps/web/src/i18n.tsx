export type Locale = keyof typeof copy;
export type Copy = { [Key in keyof (typeof copy)["ro"]]: string };

const LocaleContext = createContext<{ locale: Locale; t: Copy; toggle: () => void } | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => (localStorage.getItem("kinora-locale") === "en" ? "en" : "ro"));
  const value = useMemo(
    () => ({
      locale,
      t: copy[locale],
      toggle: () => {
        const next = locale === "ro" ? "en" : "ro";
        localStorage.setItem("kinora-locale", next);
        setLocale(next);
      },
    }),
    [locale],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("locale");
  return value;
}
