// Builds the TV shell into one classic script and stylesheet, then copies it into each TV package.
//   node build.mjs           build dist/ and apps/tv/tizen, apps/tv/webos
//   node build.mjs --serve   rebuild on change and serve dist/ on http://localhost:5175
//
// A classic (non-module) script on purpose: packaged TV apps load from file://, where Chromium refuses
// module scripts, and the oldest supported TVs (webOS 4, Tizen 4) predate much of ES2017.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const here = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(here, "dist");
const tvDir = path.resolve(here, "../tv");
const serve = process.argv.includes("--serve");

/** Per platform: extra script tags the platform needs before the shell runs. */
const PLATFORMS = {
  browser: { dir: dist, head: "" },
  // webapis.js gives the shell the TV's IP address (subnet scan) and model name.
  tizen: { dir: path.join(tvDir, "tizen"), head: '<script src="$WEBAPIS/webapis/webapis.js"></script>' },
  webos: { dir: path.join(tvDir, "webos"), head: "" },
};

function html(platform, head) {
  return `<!doctype html>
<html>
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>Kinora</title>
    <link rel="stylesheet" href="shell.css" />
    <!-- Generated by apps/tv-shell/build.mjs; edit apps/tv-shell instead. -->
    <script>window.KINORA_PLATFORM = ${JSON.stringify(platform)};</script>
    ${head}
  </head>
  <body>
    <main id="view"></main>
    <iframe id="frame" hidden src="about:blank" allow="autoplay; fullscreen; encrypted-media" allowfullscreen></iframe>
    <script src="shell.js"></script>
  </body>
</html>
`;
}

const options = {
  entryPoints: { shell: path.join(here, "src/main.ts") },
  bundle: true,
  format: "iife",
  target: ["es2015", "chrome53"],
  minify: !serve,
  sourcemap: serve ? "inline" : false,
  outdir: dist,
  logLevel: "info",
};

/** The dev server writes only dist/, so the TV packages always hold a production build. */
function writePages(only) {
  for (const [platform, { dir, head }] of Object.entries(PLATFORMS)) {
    if (only && platform !== only) continue;
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "index.html"), html(platform, head));
    if (dir === dist) continue;
    for (const file of ["shell.js", "shell.css"]) fs.copyFileSync(path.join(dist, file), path.join(dir, file));
  }
}

if (serve) {
  const context = await esbuild.context({
    ...options,
    plugins: [{ name: "pages", setup: (build) => build.onEnd((result) => result.errors.length === 0 && writePages("browser")) }],
  });
  await context.watch();
  const { port } = await context.serve({ servedir: dist, port: 5175 });
  console.log(`Shell on http://localhost:${port}/`);
} else {
  fs.rmSync(dist, { recursive: true, force: true });
  await esbuild.build(options);
  writePages();
  console.log("Shell copied into apps/tv/tizen and apps/tv/webos.");
}
